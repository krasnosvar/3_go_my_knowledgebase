package main

import (
	"context"
	"database/sql"
	"fmt"
	"log"
	"os"
	"sync"
	"time"

	_ "github.com/jackc/pgx/v5/stdlib" // Standard library compatible driver
)

/*
═══════════════════════════════════════════════════════════════════════════════
ОПИСАНИЕ ПРОГРАММЫ: Демонстрация Worker Pool паттерна для конкурентных UPDATE'ов
═══════════════════════════════════════════════════════════════════════════════

ЧТО ДЕЛАЕТ ПРОГРАММА:
1. Создает таблицу users с 1 миллионом записей
2. Обновляет все записи конкурентно через пул воркеров
3. Каждый воркер обрабатывает свою порцию записей из общей очереди

ПАТТЕРН WORKER POOL:
- Фиксированное количество горутин (100 воркеров)
- Общая очередь задач (канал jobs)
- Воркеры конкурентно "вытаскивают" задачи из канала
- Когда канал закрывается и опустошается → воркеры завершаются

ПРЕИМУЩЕСТВА ПОДХОДА:
✅ Контролируемая нагрузка (не 1 млн горутин, а только 100)
✅ Автоматическое распределение работы между воркерами
✅ Эффективное использование пула соединений БД
✅ Простая синхронизация через WaitGroup

НЕДОСТАТКИ ТЕКУЩЕЙ РЕАЛИЗАЦИИ:
❌ 1 миллион отдельных UPDATE запросов (медленно)
❌ 1 миллион принтов в консоль (тормозит программу)
❌ log.Fatalf в горутинах (убьет всю программу при одной ошибке)

АЛЬТЕРНАТИВА: Батчи по 10,000 записей = 100 UPDATE'ов вместо 1 млн
═══════════════════════════════════════════════════════════════════════════════
*/

const batchSize = 100000 // Константа для будущих экспериментов (сейчас не используется)

func main() {
	// ═══════════════════════════════════════════════════════════════════════
	// 1. ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ
	// ═══════════════════════════════════════════════════════════════════════

	// Берем строку подключения из переменной окружения (для продакшена)
	// или используем дефолтную для локальной разработки
	connStr := os.Getenv("DATABASE_URL")
	if os.Getenv("DATABASE_URL") == "" {
		connStr = "postgres://postgres:admin@localhost:5432/postgres?sslmode=disable"
	}
	log.Println("Using connection string:", connStr)

	// Открываем соединение с БД (но еще не подключаемся!)
	db, err := sql.Open("pgx", connStr)
	if err != nil {
		log.Fatalf("Unable to connect to database: %v\n", err)
	}
	defer db.Close() // Гарантируем закрытие при выходе из main()

	// ВАЖНО: Настройка пула соединений для конкурентной работы
	db.SetMaxOpenConns(100)                // Макс 100 одновременных соединений (= кол-ву воркеров)
	db.SetMaxIdleConns(10)                 // Держим 10 соединений "на подхвате"
	db.SetConnMaxLifetime(time.Minute * 5) // Переоткрываем соединения каждые 5 минут

	// Проверяем, что БД реально доступна (настоящее подключение)
	err = db.Ping()
	if err != nil {
		log.Fatalf("Database unreachable: %v\n", err)
	}
	fmt.Println("Successfully connected!")

	// ═══════════════════════════════════════════════════════════════════════
	// 2. ИНИЦИАЛИЗАЦИЯ: Создание и наполнение таблицы
	// ═══════════════════════════════════════════════════════════════════════

	query := `
	DROP TABLE IF EXISTS users;  -- Удаляем старую таблицу, если есть

	CREATE TABLE users (
		id SERIAL PRIMARY KEY,     -- Автоинкрементный ID (1, 2, 3...)
		name VARCHAR(255),         -- Случайное имя
		order_count INT            -- Счетчик заказов (изначально 0)
	);

	-- Генерируем 1 миллион записей за один запрос
	INSERT INTO users (name, order_count)
	SELECT 
		-- Случайно выбираем имя из массива
		(ARRAY[
			'Den', 'Max', 'John', 'Bob', 'Alice', 
			'Ann', 'Vasya', 'Petya', 'Masha', 'Olya'
		])[floor(random() * 10 + 1)], 
		0  -- Всем ставим order_count = 0
	FROM generate_series(1, 1000000);  -- Генерируем 1 млн строк
	`

	start := time.Now()

	// Используем контекст с таймаутом (вставка 1 млн строк может занять 5-10 сек)
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel() // Освобождаем ресурсы контекста

	_, err = db.ExecContext(ctx, query)
	if err != nil {
		log.Fatalf("Ошибка при выполнении инициализации: %v", err)
	}
	fmt.Printf("Готово! 1 000 000 строк добавлено за %v\n", time.Since(start))

	// ═══════════════════════════════════════════════════════════════════════
	// 3. ПОДСЧЕТ СТРОК В ТАБЛИЦЕ
	// ═══════════════════════════════════════════════════════════════════════

	var totalRows int
	// QueryRow - для запросов, возвращающих одну строку
	// Scan - "распаковывает" результат в переменную totalRows
	err = db.QueryRow("SELECT COUNT(*) FROM users").Scan(&totalRows)
	if err != nil {
		log.Fatalf("Failed to fetch count: %v", err)
	}
	fmt.Printf("Fetched count: %d\n", totalRows)

	// ═══════════════════════════════════════════════════════════════════════
	// 4. WORKER POOL: Конкурентное обновление записей
	// ═══════════════════════════════════════════════════════════════════════

	const numWorkers = 100 // Количество одновременно работающих горутин

	// ───────────────────────────────────────────────────────────────────────
	// 4.1. Создание канала для очереди задач
	// ───────────────────────────────────────────────────────────────────────
	// Буферизированный канал вмещает все задачи (1 млн ID)
	// Это позволяет главной горутине быстро "сбросить" все задачи
	// и не блокироваться на отправке в канал
	jobs := make(chan int, totalRows)

	// WaitGroup - счетчик для ожидания завершения всех воркеров
	var wg sync.WaitGroup

	// ───────────────────────────────────────────────────────────────────────
	// 4.2. Запуск воркеров (горутин-обработчиков)
	// ───────────────────────────────────────────────────────────────────────
	// Запускаем 100 горутин, каждая будет "вытаскивать" задачи из канала jobs
	for w := 0; w < numWorkers; w++ {
		wg.Add(1) // Увеличиваем счетчик WaitGroup на 1 (ждем эту горутину)

		go func() { // Запускаем горутину-воркер
			defer wg.Done() // При завершении горутины уменьшаем счетчик WaitGroup

			// БЕСКОНЕЧНЫЙ ЦИКЛ: читаем из канала, пока он не закроется
			// Когда канал закрывается и пустеет → цикл завершается
			for userID := range jobs {

				// ───────────────────────────────────────────────────────
				// Обновление ОДНОЙ записи
				// ───────────────────────────────────────────────────────
				updQuery := `
					UPDATE users 
					SET order_count = 1 
					WHERE id = $1 AND order_count = 0
				`
				// Выполняем UPDATE для конкретного ID
				result, err := db.Exec(updQuery, userID)
				if err != nil {
					// ❌ ПРОБЛЕМА: log.Fatalf убьет ВСЮ программу
					// Лучше: log.Printf("Error: %v", err) + continue
					log.Fatalf("Ошибка при выполнении запроса: %v", err)
				}

				// Проверяем, была ли реально обновлена строка
				rowsAffected, _ := result.RowsAffected()
				if rowsAffected == 0 {
					// ❌ ПРОБЛЕМА: 1 миллион таких принтов замедлят программу!
					fmt.Println("Запись не обновлена (либо ID не найден, либо значение уже не 0)")
				} else {
					// ❌ ПРОБЛЕМА: Миллион принтов в консоль = ОЧЕНЬ медленно
					// Лучше: логировать только ошибки или использовать счетчик
					fmt.Printf("Поле успешно обновлено для ID: %d\n", userID)
				}
			}
			// Когда канал jobs закроется и опустеет → for завершится
			// defer wg.Done() сработает автоматически
		}()
	}

	// На этом моменте:
	// ✅ 100 воркеров запущены и ждут задач из канала jobs
	// ✅ Главная горутина продолжает выполнение дальше

	// ───────────────────────────────────────────────────────────────────────
	// 4.3. Отправка задач в канал (главная горутина)
	// ───────────────────────────────────────────────────────────────────────
	// Помещаем в канал все ID от 1 до 1,000,000
	// Воркеры параллельно "разбирают" их из канала
	for userID := 1; userID <= totalRows; userID++ {
		jobs <- userID // Отправляем ID в канал
		// Благодаря буферу канала (totalRows), главная горутина не блокируется
	}

	// ВАЖНО: Закрываем канал, сигнализируя воркерам "больше задач не будет"
	// После этого воркеры обработают оставшиеся задачи и завершатся
	close(jobs)

	// ───────────────────────────────────────────────────────────────────────
	// 4.4. Ожидание завершения всех воркеров
	// ───────────────────────────────────────────────────────────────────────
	// Блокируем главную горутину до тех пор, пока:
	// - Все 100 воркеров не обработают свои задачи
	// - Все 100 воркеров не вызовут wg.Done()
	// - Счетчик WaitGroup не обнулится
	wg.Wait()

	fmt.Println("Все записи обновлены!")

	// После wg.Wait() гарантируется, что:
	// ✅ Все 1,000,000 UPDATE'ов выполнены
	// ✅ Все 100 воркеров завершились
	// ✅ Можно безопасно завершать программу
}

/*
═══════════════════════════════════════════════════════════════════════════════
КАК РАБОТАЕТ WORKER POOL В ЭТОМ КОДЕ:

1. ГЛАВНАЯ ГОРУТИНА:
   ┌─────────────────┐
   │  for ID 1..1млн │
   │  jobs <- ID     │  ← Кладет все ID в канал
   │  close(jobs)    │
   └─────────────────┘
           │
           ▼
   ┌──────────────────┐
   │  Канал jobs      │  ← Буфер на 1 млн элементов
   │  [1,2,3...1000000]│
   └──────────────────┘
           │
           ├────────┬────────┬────────┬─────┬────────┐
           ▼        ▼        ▼        ▼     ▼        ▼
   ┌─────────┐┌─────────┐┌─────────┐...  ┌─────────┐
   │Worker #1││Worker #2││Worker #3│     │Worker100│
   │UPDATE ID││UPDATE ID││UPDATE ID│     │UPDATE ID│
   └─────────┘└─────────┘└─────────┘     └─────────┘
                                                ↓
                                           wg.Done()

2. РАСПРЕДЕЛЕНИЕ РАБОТЫ:
   - Worker #1 может взять ID: 1, 101, 201, 301... (случайно)
   - Worker #2 может взять ID: 2, 102, 202, 302...
   - Не гарантируется порядок обработки!
   - Воркеры "соревнуются" за задачи из канала

3. ЗАВЕРШЕНИЕ:
   - close(jobs) → сигнал "новых задач не будет"
   - Воркеры дочитывают канал и завершаются
   - wg.Wait() → ждет, пока все 100 Done() не вызовутся

═══════════════════════════════════════════════════════════════════════════════
*/
