-- ============================================================
-- Решение задачи 4: LEFT JOIN — клиенты и заказы
-- ============================================================

-- ============================================================
-- ЧАСТЬ A: Все клиенты + сумма завершённых заказов
-- ============================================================

SELECT
    c.name,                                     -- имя клиента
    c.industry,                                 -- индустрия
    COALESCE(SUM(o.amount), 0) AS total_amount  -- сумма завершённых заказов
    --       ^^^^^^^^^^^^^^^^^
    -- COALESCE нужен здесь! SUM возвращает NULL, если нет строк для суммирования.
    -- COALESCE(NULL, 0) → 0.
    -- (В отличие от COUNT, который возвращает 0, SUM возвращает NULL)
FROM clients c
    LEFT JOIN orders o ON c.id = o.client_id
                       AND o.status = 'completed'
    -- ⚠️ ВАЖНО: условие status = 'completed' в ON, а НЕ в WHERE!
    --
    -- Если поставить в WHERE — LEFT JOIN превратится в INNER JOIN,
    -- потому что для клиентов без завершённых заказов o.status будет NULL,
    -- и условие NULL = 'completed' → false → строка отфильтруется.
    --
    -- Правило: дополнительные условия к правой таблице LEFT JOIN
    -- всегда ставьте в ON, не в WHERE.
GROUP BY c.id, c.name, c.industry
ORDER BY total_amount DESC;

-- РЕЗУЛЬТАТ:
-- +---------------------+-----------+-------------+
-- | name                | industry  | total_amount|
-- +---------------------+-----------+-------------+
-- | ООО «Ромашка»       | Ритейл    |     5000000 |
-- | Global Trade Ltd.   | Финансы   |     3000000 |
-- | ИП Сергеев          | Логистика |     3000000 |
-- | TechCorp Inc.       | IT        |           0 |  ← есть заказы, но не 'completed'
-- | ООО «Пустышка»      | Консалтинг|           0 |  ← нет заказов вообще
-- +---------------------+-----------+-------------+

-- ============================================================
-- ЧАСТЬ B: Клиенты без заказов
-- ============================================================

-- Вариант 1: LEFT JOIN + IS NULL (наиболее распространённый)
SELECT
    c.name,
    c.country
FROM clients c
    LEFT JOIN orders o ON c.id = o.client_id
WHERE o.id IS NULL;
    -- Если после LEFT JOIN колонки из orders равны NULL —
    -- значит, у клиента нет ни одного заказа.
    -- Проверяем по o.id (PK, не может быть NULL в реальных данных).

-- Вариант 2: NOT EXISTS (часто эффективнее на больших таблицах)
SELECT
    c.name,
    c.country
FROM clients c
WHERE NOT EXISTS (
    SELECT 1 FROM orders o WHERE o.client_id = c.id
);
    -- NOT EXISTS возвращает true, если подзапрос не вернул строк.
    -- PostgreSQL оптимизирует NOT EXISTS с Anti Join — может быть
    -- быстрее LEFT JOIN + IS NULL на больших объёмах данных.

-- Вариант 3: NOT IN (осторожно с NULL!)
SELECT
    c.name,
    c.country
FROM clients c
WHERE c.id NOT IN (SELECT client_id FROM orders);
    -- ⚠️ ПОДВОХ: если в orders.client_id есть NULL, то NOT IN
    -- вернёт пустой результат (NULL портит сравнение).
    -- Безопаснее: NOT IN (SELECT client_id FROM orders WHERE client_id IS NOT NULL)

-- РЕЗУЛЬТАТ (для всех вариантов):
-- +------------------+---------+
-- | name             | country |
-- +------------------+---------+
-- | ООО «Пустышка»   | Russia  |
-- +------------------+---------+

-- ============================================================
-- КЛЮЧЕВЫЕ МОМЕНТЫ:
-- ============================================================
--
-- 1. LEFT JOIN + условие в ON vs WHERE — это ОЧЕНЬ частый вопрос!
--    ON фильтрует ДО JOIN, WHERE — ПОСЛЕ. Для LEFT JOIN это критично.
--
-- 2. SUM возвращает NULL (не 0) → используйте COALESCE(SUM(...), 0)
--    COUNT возвращает 0 → COALESCE не обязателен
--
-- 3. Три способа найти "строки без связей":
--    LEFT JOIN + IS NULL | NOT EXISTS | NOT IN
--    На собеседовании часто просят назвать все три и сравнить.
