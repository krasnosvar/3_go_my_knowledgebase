-- ============================================================
-- Решение задачи 1: INNER JOIN — сотрудники и их отделы
-- ============================================================

-- РЕШЕНИЕ:
SELECT
    e.first_name,          -- имя сотрудника
    e.last_name,           -- фамилия
    d.name AS department,  -- название отдела (из таблицы departments)
    e.salary               -- зарплата
FROM employees e
    INNER JOIN departments d ON e.department_id = d.id
    --         ^^^^^^^^^^^
    -- INNER JOIN = обычный JOIN: возвращает только те строки,
    -- где есть совпадение в ОБЕИХ таблицах.
ORDER BY e.salary DESC;

-- РЕЗУЛЬТАТ: 9 строк (НЕ 10!)
--
-- Наталья Попова (department_id IS NULL) НЕ попадает в результат,
-- потому что INNER JOIN отбрасывает строки, где нет совпадения
-- по условию ON. NULL != любое значение → строка исключена.
--
-- Если нужно включить её — используйте LEFT JOIN (см. задачу 2).
--
-- ============================================================
-- КЛЮЧЕВЫЕ МОМЕНТЫ:
-- ============================================================
-- 1. INNER JOIN = JOIN — это одно и то же, слово INNER опционально
-- 2. INNER JOIN отбрасывает строки без совпадения в ОБЕИХ таблицах
-- 3. Алиасы (e, d) делают запрос читаемее и короче
-- 4. При одинаковых именах колонок нужно явно указывать таблицу
