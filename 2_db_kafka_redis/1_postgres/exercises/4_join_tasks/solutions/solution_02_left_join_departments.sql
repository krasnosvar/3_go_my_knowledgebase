-- ============================================================
-- Решение задачи 2: LEFT JOIN — отделы и количество сотрудников
-- ============================================================

-- РЕШЕНИЕ:
SELECT
    d.name,                                 -- название отдела
    COUNT(e.id) AS employee_count           -- количество сотрудников
    --    ^^^^
    -- ВАЖНО: COUNT(e.id), а НЕ COUNT(*)!
    -- COUNT(*) считает ВСЕ строки, включая NULL (даст 1 для Analytics).
    -- COUNT(e.id) считает только НЕ-NULL значения (даст 0 для Analytics).
FROM departments d
    LEFT JOIN employees e ON d.id = e.department_id
    -- LEFT JOIN: все строки из ЛЕВОЙ таблицы (departments) всегда
    -- присутствуют в результате. Если в правой таблице (employees)
    -- нет совпадений — колонки из неё будут NULL.
GROUP BY d.id, d.name
    -- GROUP BY d.id достаточно (id — PK), но d.name добавлен
    -- для читаемости. PostgreSQL позволяет не указывать d.name,
    -- если d.id — PK, но MySQL и MSSQL — нет.
ORDER BY employee_count DESC;

-- РЕЗУЛЬТАТ:
-- +-----------+----------------+
-- | name      | employee_count |
-- +-----------+----------------+
-- | Backend   |              3 |
-- | Frontend  |              2 |
-- | QA        |              2 |
-- | DevOps    |              2 |
-- | Analytics |              0 |  ← LEFT JOIN сохранил этот отдел!
-- +-----------+----------------+

-- ============================================================
-- ТИПИЧНЫЕ ОШИБКИ:
-- ============================================================
--
-- Ошибка 1: использовать INNER JOIN вместо LEFT JOIN
--   → отдел Analytics (без сотрудников) пропадёт из результата
--
-- Ошибка 2: использовать COUNT(*) вместо COUNT(e.id)
--   → для Analytics выдаст 1, а не 0
--   Потому что LEFT JOIN создаёт одну строку с NULL-значениями,
--   и COUNT(*) считает эту строку.
--
