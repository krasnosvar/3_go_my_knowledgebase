// Пример 01: in-memory очередь на буферизованном канале.
//
// Продюсер отправляет N сообщений в буферизованный канал (роль очереди),
// консьюмер их обрабатывает. Синхронизация — через WaitGroup и close(chan):
// продюсер закрывает канал, консьюмер дочитывает остаток по range и
// сообщает о завершении. Никаких sleep — программа детерминированно
// обрабатывает все N сообщений и завершается.
//
// Демонстрирует: канал как очередь, продюсер/консьюмер, корректное
// завершение через close(chan) + sync.WaitGroup.
package main

import (
	"fmt"
	"sync"
)

func main() {
	fmt.Println("--- 01_inmem_queue ---")

	const n = 5

	// Буферизованный канал играет роль очереди сообщений.
	queue := make(chan string, 3)

	var wg sync.WaitGroup

	// Консьюмер: читает очередь, пока она не закрыта и не опустела.
	var processed int
	wg.Add(1)
	go func() {
		defer wg.Done()
		// range по каналу завершится, когда канал закрыт и опустошён.
		for msg := range queue {
			processed++
			fmt.Printf("консьюмер обработал: %s\n", msg)
		}
	}()

	// Продюсер: шлёт N сообщений и закрывает канал (сигнал «больше не будет»).
	for i := 1; i <= n; i++ {
		msg := fmt.Sprintf("msg-%d", i)
		queue <- msg
		fmt.Printf("продюсер отправил: %s\n", msg)
	}
	close(queue)

	// Ждём, пока консьюмер дочитает всё, и выходим.
	wg.Wait()

	fmt.Printf("отправлено=%d обработано=%d\n", n, processed)
	if processed == n {
		fmt.Println("PASS: все сообщения обработаны ровно один раз")
	} else {
		fmt.Println("FAIL: обработано не столько, сколько отправлено")
	}
}
