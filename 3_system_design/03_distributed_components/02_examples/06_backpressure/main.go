// Пример 06: backpressure на канале с маленьким буфером.
//
// Продюсер быстрый, консьюмер медленный. Буфер канала маленький (2). Когда
// буфер заполнен, следующий send блокируется — это и есть backpressure:
// продюсер вынужден ждать, пока консьюмер освободит место.
//
// Чтобы показать это ДЕТЕРМИНИРОВАННО и БЕЗ sleep, мы делаем так:
//   - консьюмер забирает по одному элементу только когда продюсер разрешит
//     ему это, послав сигнал в канал step;
//   - перед каждой отправкой продюсер пробует НЕблокирующий send (select с
//     default). Если буфер полон (default сработал) — это зафиксированный
//     backpressure: продюсер увеличивает счётчик blocked, разрешает консьюмеру
//     сделать один шаг (освободить место) и повторяет уже блокирующий send.
//
// Так порядок событий строго детерминирован: буфер=2 переполняется на 3-й
// отправке, и мы наблюдаем ровно ожидаемое число блокировок. Завершение —
// через close(chan) + WaitGroup.
//
// Демонстрирует: backpressure, блокировку продюсера при полном буфере,
// flow control через каналы (без sleep-«на удачу»).
package main

import (
	"fmt"
	"sync"
)

func main() {
	fmt.Println("--- 03_backpressure ---")

	const (
		n    = 5 // сколько сообщений произвести
		bufN = 2 // размер буфера очереди
	)

	data := make(chan int, bufN)
	step := make(chan struct{}) // продюсер разрешает консьюмеру забрать один элемент

	var wg sync.WaitGroup
	var received int

	// Консьюмер: делает receive только по разрешению (step). Это моделирует
	// медленного получателя, темп которого задаёт синхронизация, а не sleep.
	wg.Add(1)
	go func() {
		defer wg.Done()
		for range step {
			v := <-data
			received++
			fmt.Printf("consumer принял %d (в буфере осталось %d)\n", v, len(data))
		}
	}()

	blocked := 0 // сколько раз продюсер упёрся в полный буфер (backpressure)

	for i := 1; i <= n; i++ {
		// Пробуем отправить без блокировки.
		select {
		case data <- i:
			fmt.Printf("producer отправил %d сразу (буфер занят на %d/%d)\n", i, len(data), bufN)
		default:
			// Буфер полон -> backpressure. Разрешаем консьюмеру освободить
			// место.
			blocked++
			fmt.Printf("producer ЗАБЛОКИРОВАН на %d: буфер полон (%d/%d), backpressure\n", i, len(data), bufN)
			step <- struct{}{} // консьюмер заберёт один элемент -> появится место
			data <- i          // теперь отправка проходит
			fmt.Printf("producer отправил %d после разблокировки\n", i)
		}
	}

	// Продюсер закончил. Разрешаем консьюмеру дочитать всё, что осталось.
	// Осталось ровно len(data) элементов в буфере.
	remaining := len(data)
	for j := 0; j < remaining; j++ {
		step <- struct{}{}
	}
	close(step)

	wg.Wait()

	fmt.Printf("отправлено=%d принято=%d блокировок(backpressure)=%d\n", n, received, blocked)

	// Буфер = 2. Отправки 1,2 идут сразу. Отправка 3 упирается в полный буфер
	// -> дальше каждая отправка требует освобождения места -> блокировки на
	// 3,4,5.
	wantBlocked := n - bufN
	if received == n && blocked == wantBlocked {
		fmt.Printf("PASS: продюсер блокировался %d раз (ожидалось %d), все %d приняты\n",
			blocked, wantBlocked, n)
	} else {
		fmt.Println("FAIL: неверное число блокировок или потеряны сообщения")
	}
}
